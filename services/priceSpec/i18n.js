const LANGS = Object.keys(STRINGS);

function resolveLang(lang) {
  const short = String(lang || '').slice(0, 2).toLowerCase();
  return LANGS.includes(short) ? short : 'en';
}

/** Słownik z podstawianiem `{nazwa}`. */
function translator(lang) {
  const dict = STRINGS[resolveLang(lang)];
  return (key, vars) => {
    const text = dict[key] ?? STRINGS.en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (ph, name) => (name in vars ? String(vars[name]) : ph)) : text;
  };
}

module.exports = { STRINGS, translator, resolveLang };
